import { createRequire } from 'module'; const { chromium } = createRequire(import.meta.url)('playwright');
const [,, url, out, w='900', h='600'] = process.argv;
const b = await chromium.launch({args:['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const p = await b.newPage({viewport:{width:+w,height:+h}});
p.on('console', m => console.log('console:', m.text()));
p.on('pageerror', e => console.log('pageerror:', e.message));
await p.goto(url); await p.waitForFunction(() => document.title === 'ok', null, {timeout: 60000});
await p.waitForTimeout(+(process.env.WAIT||300));
if (process.env.INFO) console.log(JSON.stringify(await p.evaluate(() => window.INFO)));
await p.screenshot({path: out}); await b.close();
