// partita contro la CPU con mouse e tastiera: menu, nome, controller, partita a 1 game fino alla fine, rivincita, pausa
import { readFileSync } from 'node:fs';
import { launch, page, check, summary, SP } from './th.mjs';
const bots = readFileSync(new URL('./bots.js', import.meta.url), 'utf8');
const B = await launch();
const { p, errs } = await page(B, 'http://127.0.0.1:8765/tennis/?q=low');
await p.waitForFunction(() => window.__racchetta, null, { timeout: 60000 });
await p.screenshot({ path: SP + '/cpu-menu.png' });
check('menu: arena in giro e due modalità', await p.evaluate(() => __racchetta.state === 'menu' && !!document.querySelector('#btnCpu') && !!document.querySelector('#btnInvite')));
await p.fill('#name', 'Sergio'); await p.click('#fmt [data-v="1"]');
await p.click('#btnCpu');
check('scelta del controller esplicita', await p.evaluate(() => !document.querySelector('#ctrl').classList.contains('hidden')));
await p.click('#ctrlMouse');
await p.waitForFunction(() => __racchetta.state === 'play');
check('partita avviata: tabellone con il nome', /Sergio/.test(await p.textContent('#score')));
const x0 = await p.evaluate(() => __racchetta.core.players[0].x);
await p.keyboard.down('KeyD'); await p.waitForTimeout(700); await p.keyboard.up('KeyD');
check('tastiera: D sposta il giocatore a mano', await p.evaluate(x => __racchetta.core.players[0].x > x + .3, x0));
await p.addScriptTag({ content: bots });
await p.evaluate(() => { __mouseBot({ sd: .05 });
  window.__ev = { contact: [], miss: [], points: [0, 0], hits: 0 };
  const c = __racchetta.core, u = c.update.bind(c);
  c.update = (dt, inp) => { const ev = u(dt, inp); for (const e of ev){ if (e.type === 'contact' && e.player === 'me') __ev.contact.push(e.label); if (e.type === 'miss' && e.player === 'me') __ev.miss.push(e.why); if (e.type === 'point') __ev.points[e.team]++; if (e.type === 'hit') __ev.hits++; } return ev; };
});
await p.waitForTimeout(4000);
await p.screenshot({ path: SP + '/cpu-play.png' });
const t0 = Date.now(); let end = false;
while (Date.now() - t0 < 420000){ if (await p.evaluate(() => __racchetta.state === 'end')){ end = true; break; } await p.waitForTimeout(1000); }
const ev = await p.evaluate(() => __ev);
await p.screenshot({ path: SP + '/cpu-end.png' });
check('il mouse colpisce la palla (clic al momento giusto)', ev.contact.length >= 4, `${ev.contact.length} colpi: ${ev.contact.join(', ')}; mancate: ${ev.miss.join(', ') || 'nessuna'}`);
check('la partita arriva alla fine', end, `punti ${ev.points}`);
check('schermata finale con risultato e statistiche', /Vittoria|Sconfitta/.test(await p.textContent('#endTitle')) && /Colpi perfetti/.test(await p.textContent('#endStats')));
await p.click('#again');
check('rivincita senza ricaricare: punteggio azzerato', await p.evaluate(() => __racchetta.state === 'play' && __racchetta.core.score.games.join() === '0,0'));
await p.keyboard.press('Escape');
check('Esc mette in pausa', await p.evaluate(() => __racchetta.state === 'paused'));
await p.click('#resume');
check('riprendi', await p.evaluate(() => __racchetta.state === 'play'));
await p.click('#pauseBtn'); await p.click('#toMenu');
check('torna al menu', await p.evaluate(() => __racchetta.state === 'menu'));
check('nessun errore JavaScript', !errs.length, errs.join(' | ').slice(0, 400));
summary(); await B.close();
